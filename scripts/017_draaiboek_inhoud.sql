## 4. Spreekteksten

### Spreken 1 — Na de ceremonie
Ik wil iedereen vragen om zo meteen zijn stoel op te tillen, in te klappen en in de kar te plaatsen. Daarna mogen jullie allemaal richting het terras verplaatsen. Daar krijgt een ieder wat te drinken. Het bruidspaar zal zich weer bij ons voegen en gezamenlijk zullen wij proosten. Het bruidspaar loopt liever na het proosten zelf langs iedereen, dus voel je niet verplicht om allemaal naar het bruidspaar te lopen om ze te feliciteren.

### Spreken 2 — Uitleg bingospel
Ik wil jullie uitnodigen om mee te doen met een spel. Het bruidspaar is niet vies van een spelletje, dus wil graag ook met jullie een spel spelen. Jullie krijgen zo meteen allemaal een bingokaart uitgereikt. Hier staan omschrijvingen op waar jullie personen aan moeten koppelen. Het is de bedoeling dat je op zoek gaat naar een persoon die past bij de omschrijving in één van je vakjes. Loop naar iemand toe, noem één van de omschrijvingen en vraag of deze persoon bij die omschrijving past. Als je iemand gevonden hebt die past bij één van de vakjes, vraag je deze persoon om zijn of haar naam in dat vakje te schrijven. Het is de bedoeling dat je je bingokaart zoveel als mogelijk probeert te vullen. Iedereen mag maar 1 keer zijn of haar naam in één van de vakjes op je bingokaart schrijven. Het doel van het spel is niet om te winnen, maar om ervoor te zorgen dat niemand meer een vreemde is van elkaar.

### Spreken 3 — Overgang naar diner
Wij nodigen jullie uit om naar boven te gaan en daar plaats te nemen voor het diner. Er is een tafelindeling gemaakt. Iedereen kan op zoek gaan naar zijn of haar plekje. Op de tafels vinden jullie geen normale naamkaartjes, maar omschrijvingen over jullie. Aan jullie de opdracht om de omschrijving te vinden die bij jou past. Het verzoek is om de kaartjes op de tafel te laten staan. Ben je zeker van de omschrijving? Neem dan plaats en check of je op de goede plek zit door de binnenkant van het naamkaartje te bekijken.

### Spreken 4 — Welkom avondgasten
Welkom aan een ieder van jullie op de bruiloft van Olaf & Ester. Heel fijn dat er zich zo veel mensen bij ons hebben gevoegd om er een mooi feestje van te maken vanavond. Het bruidspaar zal zich zo bij ons voegen. Als het goed is heeft iedereen zijn vingerafdruk achtergelaten op de gastenboom en heeft iedereen een briefje met een foto-opdracht gepakt. Zo niet, doe dat straks nog even. Op de tafel naast de bar staat een tafel waar nog de mogelijkheid is om een boodschap of meerdere boodschappen achter te laten voor het bruidspaar. Neem ergens gedurende de avond even de tijd om hier wat op te schrijven. Drankjes kunnen jullie zelf aan de bar bestellen. Maak ook vooral foto's tijdens het feest. Deze foto's kunnen geüpload worden in de foto-app, zie op de statafels de QR-code van de app. Leuk als iedereen zijn of haar foto's hierin wil zetten, zodat het bruidspaar en jullie zelf een mooie verzameling foto's hebben aan het einde van de avond. Het bruidspaar stelt het op prijs dat als je naar huis toe gaat, je gewoon vertrekt. Jullie hoeven het bruidspaar niet gedag te komen zeggen. Het leukste is als jullie allemaal blijven tot het einde, want dan zullen we het bruidspaar gezamenlijk uitzwaaien. Voor nu, geniet van vanavond en nu eerst: maak even ruimte voor het bruidspaar.

### Spreken 5 — Uitzwaaien
Wij willen vragen of iedereen naar buiten wil komen en in twee rijen tegenover elkaar wil gaan staan. Drink je drankje op of laat deze even staan. Gezamenlijk gaan wij het bruidspaar uitzwaaien. Buiten krijgt iedereen een sterretje. Probeer op mijn teken met zoveel mogelijk mensen tegelijkertijd je sterretje vanaf de onderkant — ik herhaal: de onderkant — aan te steken. We proberen zo veel mogelijk sterretjes tegelijkertijd te laten branden, waarna we het bruidspaar laten passeren. Daarna kan iedereen rustig zijn spullen pakken.

